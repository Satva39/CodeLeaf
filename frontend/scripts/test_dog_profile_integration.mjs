import fs from "node:fs";
import assert from "node:assert/strict";

const read = (path) => fs.readFileSync(new URL(path, import.meta.url), "utf8");
const header = read("../src/components/layout/Header.jsx");
const context = read("../src/components/avatar/DogAvatarContext.jsx");
const profile = read("../src/pages/ProfilePage.jsx");
const editor = read("../src/components/avatar/DogAvatarEditor.jsx");
const app = read("../src/App.jsx");
const achievementNotice = read("../src/components/avatar/AchievementRewardNotice.jsx");
const leaderboard = read("../src/pages/LeaderboardPage.jsx");
const renderer = read("../src/components/avatar/DogAvatar.jsx");
const itemArtwork = read("../src/components/avatar/avatarItemArtwork.js");
const publicProfile = read("../src/pages/PublicProfilePage.jsx");

assert.match(header, /if \(!variant \|\| variant === "dog"\)/, "default profile avatar must render the dog");
assert.match(header, /<DogAvatar/, "shared profile avatar must use the dog renderer");
assert.match(header, /useDogAvatar/, "header avatar must read account dog state");
assert.match(context, /\/api\/me\/avatar/, "shared dog state must load the authenticated avatar API");
assert.match(context, /codeleaf:dog-avatar-changed/, "customization updates must refresh shared profile pictures");
assert.match(profile, /Edit profile/, "profile must expose an Edit profile action");
assert.match(profile, /<DogAvatarEditor compact \/>/, "dog customization must live inside Edit profile");
assert.match(profile, /<Avatar size="xl" \/>/, "main profile image must use the dog avatar");
assert.doesNotMatch(profile, /AVATAR STUDIO|avatars\.map|avatarPick/, "legacy generic icon selector must be removed from profile editing");
assert.match(editor, /\/api\/me\/avatar/, "the editor must save the profile dog through the shared avatar API");
assert.match(editor, /method: "PUT"/, "appearance and equipment must save atomically");
assert.match(editor, /Preview item/, "owned items must be previewable before saving");
assert.match(editor, /Discard preview/, "unsaved changes must be cancellable");
assert.match(editor, /Save changes/, "the learner must explicitly save avatar changes");
assert.doesNotMatch(editor, /\/api\/me\/avatar\/appearance|\/api\/me\/avatar\/equipment/, "the editor must not persist each click immediately");
assert.match(editor, /AvatarItemArtwork/, "wardrobe cards must preview each item on the shared dog character");
assert.match(renderer, /dog-avatar-2d/, "the shared dog renderer must use the flat 2D character style");
assert.doesNotMatch(renderer, /<image\b|linearGradient|feGaussianBlur/, "the character must not be built from floating product images or 3D-style effects");
assert.match(itemArtwork, /<DogAvatar/, "catalog cards must show cosmetics worn on the same dog renderer");
assert.doesNotMatch(editor, /profile-dog-achievements|avatar\.achievements/, "the long achievement catalogue must not appear in the dog editor");
assert.match(itemArtwork, /AVATAR_ITEM_ARTWORK/, "every cosmetic artwork mapping must have one shared registry");
assert.match(publicProfile, /credentials: "omit"/, "public profile requests must not depend on an authenticated session");
assert.match(publicProfile, /api\/public-profiles/, "public profile must load through the dedicated public API");
assert.match(app, /path="\/avatar" element={<Navigate to="\/profile\?edit=1#dog-avatar" replace \/>}/, "legacy avatar URL must redirect into profile editing");
assert.match(app, /path="\/u\/:username" element={<PublicProfilePage \/>}/, "public profile route must resolve usernames");
assert.match(profile, /api\/me\/public-profile/, "profile settings must load through the authenticated public-profile API");
assert.match(profile, /Publish profile/, "the owner must be able to publish their profile");
assert.match(profile, /Make profile private/, "the owner must be able to unpublish their profile");
assert.match(profile, /Copy link/, "the profile URL must be copyable");
assert.match(profile, /publicProfileUrl/, "the username-based public URL must be shown even while private");
assert.match(profile, /setAccountUsername/, "the public link must use the server-confirmed account username");
assert.match(profile, /payload\.profile_path/, "the canonical profile path returned by the API must be retained");
assert.doesNotMatch(profile, /String\(handle \|\| ""\)/, "an unsaved local handle must not control whether the public link appears");
assert.doesNotMatch(header, /Dog Avatar Studio/, "separate studio navigation must be removed");
assert.match(achievementNotice, /\/profile\?edit=1#dog-avatar/, "reward links must open profile dog customization");
assert.match(leaderboard, /dogAvatar=\{row\.dog_avatar\}/, "leaderboard profile pictures must use each learner's dog");

console.log("Dog profile integration contract passed.");
