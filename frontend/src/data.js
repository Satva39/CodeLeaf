export function groupsForCourse(slug) {
  // HTML lessons are loaded exclusively from the imported course API.
  // There is intentionally no old hard-coded HTML lesson tree to fall back to.
  if (slug === "html") return [];
  if (starterGroups[slug]) return starterGroups[slug];
  const c = COURSE_CATALOG.find((x) => x.slug === slug) || COURSE_CATALOG[0];
  const key = c.title.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  return [
    {
      title: `${c.title.toUpperCase()} TUTORIAL`,
      items: [
        [`${key}-home`, `${c.title} Home`],
        [`${key}-intro`, `${c.title} Introduction`],
        [`${key}-setup`, "Setup & First Example"],
        [`${key}-core`, "Core Concepts"],
        [`${key}-practice`, "Exercises"],
      ],
    },
  ];
}

export function flattenGroups(groups) {
  return groups.flatMap((group) =>
    group.items.map(([slug, title]) => ({ slug, title, group: group.title })),
  );
}

