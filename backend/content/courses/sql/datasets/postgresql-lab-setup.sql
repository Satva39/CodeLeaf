-- CodeLeaf SQL lab setup — PostgreSQL 15+ (recommended: PostgreSQL 18)
-- Run only in a dedicated disposable practice database named codeleaf_sql_lab.
-- This reset script DROPS and recreates tables in the current database. Never run it on production.

DROP TABLE IF EXISTS schema_migrations, temporal_records, activity_events, inventory_movements,
  payments, order_items, orders, products, categories, customers, student_subjects, subjects,
  students, employees, departments, accounts CASCADE;

CREATE TABLE departments (
  department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
CREATE TABLE employees (
  employee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id integer REFERENCES departments(department_id),
  manager_id integer REFERENCES employees(employee_id),
  full_name text NOT NULL,
  email text NOT NULL UNIQUE,
  salary numeric(12,2) NOT NULL CHECK (salary >= 0),
  hire_date date NOT NULL,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE students (
  student_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL,
  email text UNIQUE,
  city text,
  marks numeric(5,2) CHECK (marks BETWEEN 0 AND 100),
  enrolled_on date NOT NULL DEFAULT CURRENT_DATE,
  phone text
);
CREATE TABLE subjects (
  subject_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_name text NOT NULL UNIQUE
);
CREATE TABLE student_subjects (
  student_id integer NOT NULL REFERENCES students(student_id),
  subject_id integer NOT NULL REFERENCES subjects(subject_id),
  marks numeric(5,2) CHECK (marks BETWEEN 0 AND 100),
  PRIMARY KEY (student_id, subject_id)
);
CREATE TABLE customers (
  customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL,
  email text NOT NULL UNIQUE,
  city text,
  phone text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE categories (
  category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
CREATE TABLE products (
  product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer REFERENCES categories(category_id),
  name text NOT NULL UNIQUE,
  price numeric(12,2) NOT NULL CHECK (price >= 0),
  stock_quantity integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE orders (
  order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(customer_id),
  order_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  status text NOT NULL CHECK (status IN ('pending','completed','cancelled')),
  total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0)
);
CREATE TABLE order_items (
  order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES products(product_id),
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  UNIQUE (order_id, product_id)
);
CREATE TABLE payments (
  payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(order_id),
  amount numeric(12,2) NOT NULL CHECK (amount >= 0),
  status text NOT NULL CHECK (status IN ('pending','captured','failed','refunded')),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE accounts (
  account_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_name text NOT NULL,
  balance numeric(12,2) NOT NULL CHECK (balance >= 0)
);
CREATE TABLE inventory_movements (
  movement_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(product_id),
  quantity_delta integer NOT NULL,
  reason text NOT NULL,
  happened_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE activity_events (
  event_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer REFERENCES customers(customer_id),
  occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE temporal_records (
  record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  valid_from timestamptz NOT NULL,
  valid_to timestamptz,
  value text NOT NULL,
  CHECK (valid_to IS NULL OR valid_to > valid_from)
);
CREATE TABLE schema_migrations (
  migration_version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

